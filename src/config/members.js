/** Members grouped by set: { 1990: [...], 1991: [...] } */
export const BY_SET = MEMBERS.reduce((acc, m) => {
  (acc[m.set] = acc[m.set] || []).push(m);
  return acc;
}, {});

/** Stable id used for the one-vote-per-person record: 1991 + sn 17 -> "1991-17". */
export function memberId(member) {
  return `${member.set}-${member.sn}`;
}

/**
 * Accepts "set of 1990", "SET OF 1990", "Setof1990", "set  of  1990" or "1990"
 * and returns 1990 (or null).
 */
export function normaliseUsername(input) {
  if (input === null || input === undefined) return null;
  const s = String(input).trim().toLowerCase().replace(/\s+/g, ' ');
  const m = s.match(/^(?:set ?of ?)?(\d{4})$/);
  return m ? Number(m[1]) : null;
}

/** The login itself: { set, sn } -> the member, or null. */
export function findMember(username, password) {
  const set = normaliseUsername(username);
  const sn = Number(String(password ?? '').trim());
  if (!set || !Number.isInteger(sn)) return null;
  return MEMBERS.find((m) => m.set === set && m.sn === sn) || null;
}

/** "Find my S/N" — look a member up by (part of) their name, optionally within a set. */
export function findMembersByName(query, set = null) {
  const q = String(query || '').trim().toLowerCase();
  if (q.length < 2) return [];
  return MEMBERS.filter(
    (m) => (!set || m.set === Number(set)) && m.name.toLowerCase().includes(q)
  );
}
